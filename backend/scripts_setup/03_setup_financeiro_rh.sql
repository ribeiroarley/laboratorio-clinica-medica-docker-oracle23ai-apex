-- =============================================================================
-- Script: 03_setup_financeiro_rh.sql
-- Objetivo: Criacao das Tabelas de Back-Office (RH, Financeiro e Fornecedores)
-- SGBD: Oracle Database 23ai
-- Schema: CLINICA_MEDICA
--
-- NOTA DE ARQUITETURA E INTEGRACAO:
-- Este script expande a infraestrutura do banco para o modulo de Back-Office:
-- 1. FUNCIONARIOS integrado a USUARIOS_SISTEMA (1:1 com constraint UNIQUE);
-- 2. FORNECEDORES como entidade mestre para controle de compras e despesas;
-- 3. CONTAS_PAGAR vinculado a FORNECEDORES (1:N);
-- 4. FATURAMENTO originado do atendimento em AGENDAMENTOS (1:1 com UNIQUE);
-- 5. CONTAS_RECEBER desdobrado a partir de FATURAMENTO (1:N) para fluxo de caixa.
-- =============================================================================

-- 1. Tabela de Fornecedores e Prestadores de Servico
CREATE TABLE CLINICA_MEDICA.FORNECEDORES (
    ID_FORNECEDOR   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    RAZAO_SOCIAL    VARCHAR2(150) NOT NULL,
    CNPJ            VARCHAR2(18) NOT NULL,
    TIPO_SERVICO    VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_FORNECEDORES PRIMARY KEY (ID_FORNECEDOR),
    CONSTRAINT UK_FORNECEDORES_CNPJ UNIQUE (CNPJ)
);

-- 2. Tabela de Contas a Pagar
CREATE TABLE CLINICA_MEDICA.CONTAS_PAGAR (
    ID_CONTA_PAGAR   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_FORNECEDOR    NUMBER(10) NOT NULL,
    VALOR            NUMBER(12,2) NOT NULL,
    DATA_VENCIMENTO  DATE NOT NULL,
    STATUS_PAGAMENTO VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CONTAS_PAGAR PRIMARY KEY (ID_CONTA_PAGAR),
    CONSTRAINT FK_CONTAS_PAGAR_FORNECEDOR FOREIGN KEY (ID_FORNECEDOR) 
        REFERENCES CLINICA_MEDICA.FORNECEDORES (ID_FORNECEDOR),
    CONSTRAINT CK_CONTAS_PAGAR_STATUS CHECK (STATUS_PAGAMENTO IN ('ABERTO', 'PAGO', 'VENCIDO', 'CANCELADO')),
    CONSTRAINT CK_CONTAS_PAGAR_VALOR CHECK (VALOR > 0)
);

-- 3. Tabela de Funcionarios (Recursos Humanos)
CREATE TABLE CLINICA_MEDICA.FUNCIONARIOS (
    ID_FUNCIONARIO   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO       NUMBER(10) NOT NULL,
    NOME             VARCHAR2(150) NOT NULL,
    CPF              VARCHAR2(14) NOT NULL,
    CARGO            VARCHAR2(80) NOT NULL,
    SALARIO          NUMBER(12,2) NOT NULL,
    DATA_CONTRATACAO DATE NOT NULL,
    CONSTRAINT PK_FUNCIONARIOS PRIMARY KEY (ID_FUNCIONARIO),
    CONSTRAINT UK_FUNCIONARIOS_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UK_FUNCIONARIOS_CPF UNIQUE (CPF),
    CONSTRAINT FK_FUNCIONARIOS_USUARIO FOREIGN KEY (ID_USUARIO) 
        REFERENCES CLINICA_MEDICA.USUARIOS_SISTEMA (ID_USUARIO),
    CONSTRAINT CK_FUNCIONARIOS_SALARIO CHECK (SALARIO > 0)
);

-- 4. Tabela de Faturamento de Consultas
CREATE TABLE CLINICA_MEDICA.FATURAMENTO (
    ID_FATURAMENTO   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_AGENDAMENTO   NUMBER(10) NOT NULL,
    VALOR_TOTAL      NUMBER(12,2) NOT NULL,
    METODO_PAGAMENTO VARCHAR2(50) NOT NULL,
    STATUS           VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_FATURAMENTO PRIMARY KEY (ID_FATURAMENTO),
    CONSTRAINT UK_FATURAMENTO_AGENDAMENTO UNIQUE (ID_AGENDAMENTO),
    CONSTRAINT FK_FATURAMENTO_AGENDAMENTO FOREIGN KEY (ID_AGENDAMENTO) 
        REFERENCES CLINICA_MEDICA.AGENDAMENTOS (ID_AGENDAMENTO),
    CONSTRAINT CK_FATURAMENTO_STATUS CHECK (STATUS IN ('PENDENTE', 'FATURADO', 'CANCELADO')),
    CONSTRAINT CK_FATURAMENTO_VALOR CHECK (VALOR_TOTAL >= 0)
);

-- 5. Tabela de Contas a Receber
CREATE TABLE CLINICA_MEDICA.CONTAS_RECEBER (
    ID_CONTA_RECEBER   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_FATURAMENTO     NUMBER(10) NOT NULL,
    VALOR              NUMBER(12,2) NOT NULL,
    DATA_VENCIMENTO    DATE NOT NULL,
    STATUS_RECEBIMENTO VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CONTAS_RECEBER PRIMARY KEY (ID_CONTA_RECEBER),
    CONSTRAINT FK_CONTAS_RECEBER_FATURAMENTO FOREIGN KEY (ID_FATURAMENTO) 
        REFERENCES CLINICA_MEDICA.FATURAMENTO (ID_FATURAMENTO),
    CONSTRAINT CK_CONTAS_RECEBER_STATUS CHECK (STATUS_RECEBIMENTO IN ('PENDENTE', 'RECEBIDO', 'VENCIDO', 'GLOSADO', 'CANCELADO')),
    CONSTRAINT CK_CONTAS_RECEBER_VALOR CHECK (VALOR > 0)
);
