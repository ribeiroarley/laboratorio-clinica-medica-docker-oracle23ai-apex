-- =============================================================================
-- Script: 01_setup_tabelas_clinica.sql
-- Objetivo: Criacao das Tabelas Centrais de Atendimento Clinico e Agendamento
-- SGBD: Oracle Database 23ai
-- Schema: CLINICA_MEDICA
--
-- NOTA DE GOVERNANCA E LGPD:
-- Em conformidade com as diretrizes corporativas de seguranca:
-- 1. Todas as declaracoes de tabelas e referencias de integridade referencial (FK)
--    utilizam explicitamente a qualificacao de schema CLINICA_MEDICA.;
-- 2. Chaves Primarias sao geradas com a clausula GENERATED ALWAYS AS IDENTITY;
-- 3. A tabela PACIENTES incorpora colunas mandatorias de consentimento LGPD
--    (TERMO_ACEITE_LGPD, DATA_CONSENTIMENTO) e CPF catalogado para Data Redaction;
-- 4. A tabela PRONTUARIOS implementa relacao 1:1 estrita com AGENDAMENTOS via UNIQUE
--    e armazena dados sensiveis de evolucao clinica em colunas CLOB.
-- =============================================================================

-- 1. Tabela de Especialidades Medicas
CREATE TABLE CLINICA_MEDICA.ESPECIALIDADES (
    ID_ESPECIALIDADE   NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOME_ESPECIALIDADE VARCHAR2(100) NOT NULL,
    DESCRICAO          VARCHAR2(500),
    STATUS_ATIVO       VARCHAR2(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_ESPECIALIDADES PRIMARY KEY (ID_ESPECIALIDADE),
    CONSTRAINT UK_ESPECIALIDADES_NOME UNIQUE (NOME_ESPECIALIDADE),
    CONSTRAINT CK_ESPECIALIDADES_STATUS CHECK (STATUS_ATIVO IN ('S', 'N'))
);

-- 2. Tabela de Medicos do Corpo Clinico
CREATE TABLE CLINICA_MEDICA.MEDICOS (
    ID_MEDICO        NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_ESPECIALIDADE NUMBER(10) NOT NULL,
    NOME_MEDICO      VARCHAR2(150) NOT NULL,
    CRM              VARCHAR2(20) NOT NULL,
    UF_CRM           VARCHAR2(2) NOT NULL,
    EMAIL            VARCHAR2(100) NOT NULL,
    TELEFONE         VARCHAR2(20),
    STATUS_ATIVO     VARCHAR2(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_MEDICOS PRIMARY KEY (ID_MEDICO),
    CONSTRAINT UK_MEDICOS_CRM_UF UNIQUE (CRM, UF_CRM),
    CONSTRAINT FK_MEDICOS_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE) 
        REFERENCES CLINICA_MEDICA.ESPECIALIDADES (ID_ESPECIALIDADE),
    CONSTRAINT CK_MEDICOS_STATUS CHECK (STATUS_ATIVO IN ('S', 'N'))
);

-- 3. Tabela de Pacientes (com atributos mandatorios LGPD)
CREATE TABLE CLINICA_MEDICA.PACIENTES (
    ID_PACIENTE        NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOME_COMPLETO      VARCHAR2(150) NOT NULL,
    CPF                VARCHAR2(14) NOT NULL,
    DATA_NASCIMENTO    DATE NOT NULL,
    SEXO_BIOLOGICO     VARCHAR2(1) NOT NULL,
    EMAIL              VARCHAR2(100),
    TELEFONE           VARCHAR2(20) NOT NULL,
    TERMO_ACEITE_LGPD  VARCHAR2(1) NOT NULL,
    DATA_CONSENTIMENTO TIMESTAMP NOT NULL,
    STATUS_CADASTRO    VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT PK_PACIENTES PRIMARY KEY (ID_PACIENTE),
    CONSTRAINT UK_PACIENTES_CPF UNIQUE (CPF),
    CONSTRAINT CK_PACIENTES_SEXO CHECK (SEXO_BIOLOGICO IN ('M', 'F', 'O')),
    CONSTRAINT CK_PACIENTES_TERMO_LGPD CHECK (TERMO_ACEITE_LGPD IN ('Y', 'N')),
    CONSTRAINT CK_PACIENTES_STATUS CHECK (STATUS_CADASTRO IN ('ATIVO', 'INATIVO', 'BLOQUEADO'))
);

-- 4. Tabela de Agendamentos de Consultas
CREATE TABLE CLINICA_MEDICA.AGENDAMENTOS (
    ID_AGENDAMENTO         NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_PACIENTE            NUMBER(10) NOT NULL,
    ID_MEDICO              NUMBER(10) NOT NULL,
    DATA_HORA_AGENDAMENTO  TIMESTAMP NOT NULL,
    STATUS_AGENDAMENTO     VARCHAR2(20) DEFAULT 'AGENDADO' NOT NULL,
    MOTIVO_CANCELAMENTO    VARCHAR2(300),
    DATA_CRIACAO           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AGENDAMENTOS PRIMARY KEY (ID_AGENDAMENTO),
    CONSTRAINT FK_AGENDAMENTOS_PACIENTE FOREIGN KEY (ID_PACIENTE) 
        REFERENCES CLINICA_MEDICA.PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_AGENDAMENTOS_MEDICO FOREIGN KEY (ID_MEDICO) 
        REFERENCES CLINICA_MEDICA.MEDICOS (ID_MEDICO),
    CONSTRAINT CK_AGENDAMENTOS_STATUS CHECK (STATUS_AGENDAMENTO IN ('AGENDADO', 'CONFIRMADO', 'CANCELADO', 'CONCLUIDO', 'NO_SHOW'))
);

-- 5. Tabela de Prontuarios Clinicos (Relacao 1:1 estrita com Agendamentos)
CREATE TABLE CLINICA_MEDICA.PRONTUARIOS (
    ID_PRONTUARIO     NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_AGENDAMENTO    NUMBER(10) NOT NULL,
    EVOLUCAO_MEDICA   CLOB NOT NULL,
    PRESCRICAO        CLOB,
    DATA_ATENDIMENTO  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS_PRONTUARIO VARCHAR2(20) DEFAULT 'FINALIZADO' NOT NULL,
    CONSTRAINT PK_PRONTUARIOS PRIMARY KEY (ID_PRONTUARIO),
    CONSTRAINT UK_PRONTUARIOS_AGENDAMENTO UNIQUE (ID_AGENDAMENTO),
    CONSTRAINT FK_PRONTUARIOS_AGENDAMENTO FOREIGN KEY (ID_AGENDAMENTO) 
        REFERENCES CLINICA_MEDICA.AGENDAMENTOS (ID_AGENDAMENTO),
    CONSTRAINT CK_PRONTUARIOS_STATUS CHECK (STATUS_PRONTUARIO IN ('EM_ANDAMENTO', 'FINALIZADO', 'RETIFICADO'))
);
